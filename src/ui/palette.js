/** hex → rgba(r,g,b,a). Нужен для теней: они строятся из брендового цвета. */
export function alpha(hex, a) {
  const h = hex.replace('#', '')
  const n = Number.parseInt(
    h.length === 3
      ? h
          .split('')
          .map((c) => c + c)
          .join('')
      : h,
    16,
  )
  // без пробелов — чтобы сборка байт-в-байт совпадала с прежними literal-тенями
  return `rgba(${(n >> 16) & 255},${(n >> 8) & 255},${n & 255},${a})`
}
