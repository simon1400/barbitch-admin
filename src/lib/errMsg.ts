// Текст ошибки для показа пользователю (этап 4.2 аудита, s185).
//
// До s185 строка `e instanceof Error ? e.message : '…'` была написана 12 раз в
// 8 файлах. Запасной текст у каждого места СВОЙ (и по языку, и по смыслу),
// поэтому он остаётся параметром — схлопывать его в одну фразу нельзя, это
// видимый пользователю текст.
export const errMsg = (e: unknown, fallback: string): string =>
  e instanceof Error ? e.message : fallback
