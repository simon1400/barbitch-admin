// Видимый текст из HTML-комментария (s189).
//
// Комментарии рабочих часов и оказанных услуг приходят из редактора Strapi как
// HTML. Все три места, которым нужен из них ТЕКСТ, делали это одинаково и
// одинаково неверно — `raw.replace(/<[^>]*>/g, '')`:
//
//   🟥 1. HTML-сущности оставались как есть, и в таблице кабинета
//         администратора было видно буквальное «&nbsp;». На проде такие
//         комментарии не редкость: 348 записей рабочих часов и 1018 оказанных
//         услуг (`&nbsp;` 1512 раз, `&quot;` 80, `&amp;` и `&gt;` по 2).
//   🟥 2. Закрывающий тег абзаца срезался в НИЧТО, и соседние абзацы
//         слипались: «<p>Убиралась</p><p>Решала машинку</p>» показывалось как
//         «УбираласьРешала машинку». Затронуто 246 записей рабочих часов и
//         172 оказанных услуг.
//
// ⚠️ Проверка «есть ли комментарий» теперь тоже идёт через эту функцию, то есть
// комментарий из одного `&nbsp;` считается ПУСТЫМ. На боевых данных это ничего
// не меняет — таких записей ноль (проверено SELECT-ом), — но защищает от
// будущих: пустой на вид комментарий не должен ни рисовать значок 💬, ни
// проходить проверку обязательного поля перед закрытием смены.

const NAMED: Record<string, string> = {
  nbsp: ' ',
  amp: '&',
  lt: '<',
  gt: '>',
  quot: '"',
  apos: "'",
}

// Разбор идёт ОДНИМ проходом, и это важно: иначе «&amp;nbsp;» после первой
// замены превратилось бы в «&nbsp;» и было бы декодировано второй — то есть
// экранированный текст молча стал бы пробелом.
const decodeEntities = (s: string): string =>
  s.replace(/&(#[xX][0-9a-fA-F]+|#\d+|[a-zA-Z][a-zA-Z0-9]*);/g, (whole, name: string) => {
    if (name.startsWith('#')) {
      const hex = name[1] === 'x' || name[1] === 'X'
      const code = Number.parseInt(hex ? name.slice(2) : name.slice(1), hex ? 16 : 10)
      if (!Number.isFinite(code) || code <= 0 || code > 0x10ffff) return whole
      try {
        return String.fromCodePoint(code)
      } catch {
        return whole // суррогат/мусорный код — оставляем как было, не роняем страницу
      }
    }
    const v = NAMED[name.toLowerCase()]
    return v === undefined ? whole : v
  })

// Блочные теги и перенос строки дают ПРОБЕЛ, остальные — ничего.
const BLOCK_TAG = /<\/(?:p|div|li|ul|ol|tr|td|th|h[1-6]|blockquote|section)\s*>|<br\s*\/?>/gi

/**
 * Текст комментария: теги сняты, сущности раскрыты, пробелы схлопнуты.
 * Не строка — пустая строка (вызывающему коду не нужно проверять тип отдельно).
 */
export const htmlToText = (raw: unknown): string => {
  if (typeof raw !== 'string' || raw === '') return ''
  return decodeEntities(raw.replace(BLOCK_TAG, ' ').replace(/<[^>]*>/g, ''))
    .replace(/\s+/g, ' ')
    .trim()
}

/** Есть ли в комментарии видимый текст. */
export const hasVisibleText = (raw: unknown): boolean => htmlToText(raw).length > 0
