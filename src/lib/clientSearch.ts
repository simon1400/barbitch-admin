// Поиск клиента по имени / телефону / почте — одна нормализация на все экраны
// (этап 5.4 аудита, s189).
//
// 🟥 Свести пришлось не «одинаковое», а РАЗОШЕДШЕЕСЯ: автокомплит календаря и
// ручная корректировка лояльности искали по-разному, и календарь искал хуже.
// Телефон в базе лежит слитно (+420777111222), а вводят его как придётся.
//   • календарь нормализовал запрос, только если тот состоял ИЗ ЦИФР, пробелов
//     и плюса — то есть «777-111-222» и «(777) 111 222» не находились вовсе;
//   • лояльность убирала ещё скобки и дефисы и находила.
// Здесь взят вариант лояльности: он строго шире, ни один прежний запрос
// результатов не теряет.
//
// ⚠️ Нормализованная форма идёт ТОЛЬКО в фильтр по телефону. Имя и почта
// ищутся по тому, что человек набрал: вычищать дефисы из имени незачем.

/** Похоже ли введённое на телефон (после снятия пробелов, скобок и дефисов). */
const phoneForm = (q: string): string | null => {
  const digits = q.replace(/[\s()-]/g, '')
  return /^\+?\d{3,}$/.test(digits) ? digits : null
}

/**
 * Фильтр `$or` по трём полям клиента. Возвращает кусок query-строки без
 * ведущего «&» — поля, сортировку и размер страницы каждый экран задаёт сам
 * (календарю нужен ещё `blacklisted`, лояльности — нет).
 */
export const clientSearchFilters = (query: string): string => {
  const enc = encodeURIComponent(query)
  const phone = encodeURIComponent(phoneForm(query) ?? query)
  return (
    `filters[$or][0][name][$containsi]=${enc}` +
    `&filters[$or][1][phone][$containsi]=${phone}` +
    `&filters[$or][2][email][$containsi]=${enc}`
  )
}

/** Клиент в подсказке поиска. Календарь расширяет её признаком чёрного списка. */
export interface ClientSearchHit {
  documentId: string
  name: string
  phone: string | null
  email: string | null
}
