// Статус брони — один словарь предикатов на все экраны (этап 5.4 аудита, s189).
//
// 🟥 Различие двух предикатов НЕ косметическое, и путать их нельзя:
//   • «состоялась» (isAttendedStatus) — клиент пришёл и заплатил. По ней считают
//     ДЕНЬГИ и посещаемость: сверка смены, зарплаты, аналитика визитов.
//   • «жива» (isActiveStatus) — слот в расписании занят. Сюда входит и noshow:
//     клиент не пришёл, но время у мастера было занято и окном не считается.
// Поэтому загрузку мастеров и свободные окна считают по второму, а деньги — по
// первому. Раньше обе формулы были расписаны литералами в восьми местах, и
// перепутать их можно было молча.
//
// Предикаты берут СТРОКУ, а не объект: одна и та же бронь приезжает в разных
// формах (HistEvent аналитики, MirrorBooking, CalendarBooking) — общий у них
// только статус.
export type BookingStatus = 'active' | 'checkedOut' | 'cancelled' | 'noshow'

/** Визит состоялся: не отменён и клиент пришёл. По этому считаются деньги. */
export const isAttendedStatus = (status: string): boolean =>
  status !== 'cancelled' && status !== 'noshow'

/** Бронь жива: слот занят. noshow тоже занимает время — свободным окном не считается. */
export const isActiveStatus = (status: string): boolean => status !== 'cancelled'
